import {mkdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {score} from '@yap/scoring';
import {testnet,ONE_YAP} from '../params.js';
import {Economy} from './economy.js';
import {attackerShares,variants} from './defences.js';
import {scenarios,SIM_SEED,SocialWorld} from './generate.js';
import type {Persona,Scenario} from './generate.js';

const root=fileURLToPath(new URL('../../',import.meta.url));
const seed=SIM_SEED;
function yap(raw:string):number {return Number((BigInt(raw)*1_000_000n/ONE_YAP))/1_000_000;}
function chance(account:string,epoch:number):number {
  let h=seed^epoch;
  for(const c of account) h=(Math.imul(h,31)+c.charCodeAt(0))>>>0;
  return h/2**32;
}
function unclaimed(pool:bigint,attention:bigint,yappers:{account:string;score:string}[],personas:Persona[],epoch:number):bigint {
  if(attention===0n||pool===0n) return 0n;
  const rates=new Map(personas.map(p=>[p.account,p.claimRate]));
  const sorted=[...yappers].sort((a,b)=>a.account<b.account?-1:a.account>b.account?1:0);
  const amounts=sorted.map(y=>pool*BigInt(y.score)/attention);
  let remainder=pool-amounts.reduce((n,x)=>n+x,0n);
  let unpaid=0n;
  for(let i=0;i<sorted.length;i++) {
    if(remainder>0n) {amounts[i]!++;remainder--;}
    const y=sorted[i]!;
    if(chance(y.account,epoch)>=(rates.get(y.account)??0.9)) unpaid+=amounts[i]!;
  }
  return unpaid;
}
interface Row {epoch:number;kind:string;supply:number;reserve:number;minted:number;burned:number;streak:number;bestStreak:number;
  attention:number;target:number;attackerShare:number|null;defences:Record<string,number|null>;yapper:number;staker:number;dao:number;reserveBurn:number;unclaimedBurn:number}
const results:Record<Scenario,Row[]>={} as Record<Scenario,Row[]>;
for(const scenario of scenarios) {
  const world=new SocialWorld(scenario),economy=new Economy(testnet),rows:Row[]=[];
  for(let epoch=0;epoch<60;epoch++) {
    const generated=world.epoch(epoch);
    const real=score(generated.dataset,generated.labels,generated.stakes,{});
    const shares=attackerShares(generated,real);
    const attention=BigInt(real.attention);
    // The R-3 arithmetic is applied once to determine the pool; claim choices only affect later burns.
    const preview=new Economy(testnet);
    Object.assign(preview,{supply:economy.supply,reserve:economy.reserve,target:economy.target,streak:economy.streak,bestStreak:economy.bestStreak});
    const draft=preview.advance(epoch,attention);
    const unpaid=unclaimed(BigInt(draft.yapper),attention,real.yappers,generated.personas,epoch);
    const e=economy.advance(epoch,attention,unpaid);
    rows.push({epoch,kind:e.kind,supply:yap(e.supply),reserve:yap(e.reserve),minted:yap(e.minted),burned:yap(e.burned),
      streak:e.streak,bestStreak:e.bestStreak,attention:Number(e.attention)/1e6,target:Number(e.target)/1e6,
      attackerShare:shares.all??null,defences:shares,yapper:yap(e.yapper),staker:yap(e.staker),dao:yap(e.dao),
      reserveBurn:yap(e.reserveBurn),unclaimedBurn:yap(e.unclaimedBurn)});
  }
  results[scenario]=rows;
  process.stdout.write(`${scenario}: supply ${rows.at(-1)!.supply.toFixed(2)} YAP, burned ${rows.reduce((n,r)=>n+r.burned,0).toFixed(2)} YAP, peak streak ${Math.max(...rows.map(r=>r.bestStreak))}\n`);
}
await mkdir(`${root}web/public`,{recursive:true});
await writeFile(`${root}web/public/sim.json`,JSON.stringify({schema:'yap-sim/1',seed,epochs:60,units:{token:'YAP',attention:'Yap score',attackerShare:'fraction of yapper emission'},
  params:testnet,variants,scenarios:results},null,2)+'\n');
function pct(n:number|null):string {return n===null?'—':`${(n*100).toFixed(1)}%`;}
const table=scenarios.map(name=>{
  const rows=results[name],last=rows.at(-1)!;
  return `| ${name} | ${last.supply.toFixed(0)} | ${last.reserve.toFixed(0)} | ${rows.reduce((n,r)=>n+r.minted,0).toFixed(0)} | ${rows.reduce((n,r)=>n+r.burned,0).toFixed(0)} | ${Math.max(...rows.map(r=>r.bestStreak))} | ${pct(last.attackerShare)} |`;
}).join('\n');
const attackTable=scenarios.filter(s=>['spam-farm','like-ring'].includes(s)).map(name=>{
  const rows=results[name];
  return `| ${name} | ${Object.keys(variants).map(v=>pct(rows.reduce((n,r)=>n+(r.defences[v]??0),0)/rows.length)).join(' | ')} |`;
}).join('\n');
const dead=results['dead-meme'];
