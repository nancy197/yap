// Writes docs/TESTNET.md and web/public/testnet.json from the real tx log and the published epoch index.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { EPOCH_DIR, ROOT, TOKEN, DAO, view } from './common.ts';

const txs: any[] = JSON.parse(await readFile(resolve(ROOT, 'deploy/transactions.json'), 'utf8'));
const idxF = resolve(ROOT, 'web/public/epochs', EPOCH_DIR, 'index.json');
const idx = existsSync(idxF) ? JSON.parse(await readFile(idxF, 'utf8')) : { epochs: {} };
const st: any = await view(TOKEN, 'get_state');
const chain: any[] = await view(TOKEN, 'get_epochs', { from: 0, limit: 200 });
const arenas: any[] = await view(TOKEN, 'get_arenas', { from: 0, limit: 50 });
const supply: string = await view(TOKEN, 'ft_total_supply');
const y = (raw: string | undefined) => (raw ? (Number(BigInt(raw) / 10n ** 15n) / 1000).toLocaleString('en-US') : '—');
const sc = (raw: string | undefined) => (raw ? (Number(raw) / 1e6).toFixed(2) : '—');
const rows = chain.sort((a, b) => a.number - b.number).map((e) => {
  const i = idx.epochs[e.number] ?? {};
  const att = e.report?.attention;
  const kind = e.status === 'Dead' ? 'dead' : i.target && att ? (BigInt(e.emission) > 0n && i.streak > 0 ? 'loud' : 'quiet') : '';
  return `| ${e.number} | ${e.status} | ${sc(att)} | ${kind} | ${y(e.emission)} | ${i.streak ?? '—'} | ${y(i.burnedTotal)} | ${y(i.supply)} | ${e.signers?.length ?? 0}/3 | ${i.posts ?? '—'} | ${i.simulatedLabels === false ? 'TEE AI' : i.simulatedLabels ? 'heuristic' : '—'} |`;
});
const groups = new Map<string, any[]>();
for (const t of txs) {
  const k = t.action.replace(/ e\d+.*$/, '').replace(/ \d+$/, '').replace(/\(.*\)/, '').trim();
  groups.set(k, [...(groups.get(k) ?? []), t]);
}
const md = `# $YAP on NEAR testnet: what ran

Generated by \`pnpm -C agents report\` from the transaction log the agents keep (\`deploy/transactions.json\`) and the
on-chain epoch records. Every hash links to testnet.nearblocks.io. Times are UTC.

- Token: [\`${TOKEN}\`](https://testnet.nearblocks.io/address/${TOKEN}). It has **no access keys**: every full-access key was deleted after init.
- Community DAO: [\`${DAO}\`](https://testnet.nearblocks.io/address/${DAO}). Sputnik DAO v2 with a council of 3; 2 votes pass a proposal.
- State now: supply ${y(supply)} YAP; minted ${y(st.minted_total)}; burned ${y(st.burned_total)}; Reserve ${y(st.reserve)}.
  Streak ${st.streak}, best streak ${st.best_streak}.
- **Simulated community.** Accounts \`y01..y24.yap-hq.testnet\` are demo personas: 15 honest (text written by \`z-ai/glm-5.3-flash\`), 4 spam bots and a 5-account like-ring.
  Their near.social writes are real testnet transactions.
- **Labels.** Post quality labels come from \`Qwen/Qwen3.8-27B\` in a TEE on NEAR AI Cloud. Its attestation is verified before every labelling run.

## Epochs

| # | status | attention | kind | emission (YAP) | streak | burned total | supply | signers | posts | labels |
| ---: | --- | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |
${rows.join('\n')}

## Arenas

${arenas.map((a) => `- #${a.id} **${a.title}** (${a.topic}), opened by \`${a.opener}\`: ${y(a.per_epoch)} per epoch for ${a.epochs} epochs from epoch ${a.start_epoch}. Budget left ${y(a.budget_left)}.`).join('\n') || 'None yet.'}

## Transactions (${txs.length})

${[...groups.entries()].map(([k, list]) => `### ${k} (${list.length})\n\n${list.map((t) => `- ${t.at.slice(0, 19).replace('T', ' ')} · ${t.action}${t.account ? ` · \`${t.account}\`` : ''} · [${t.hash.slice(0, 10)}…](${t.url})`).join('\n')}`).join('\n\n')}
`;
await mkdir(resolve(ROOT, 'docs'), { recursive: true });
await writeFile(resolve(ROOT, 'docs/TESTNET.md'), md);
await writeFile(resolve(ROOT, 'web/public/testnet.json'), JSON.stringify({ generatedAt: new Date().toISOString(), state: st, supply, epochs: chain, arenas, txCount: txs.length }, null, 1));
console.log(`wrote docs/TESTNET.md (${txs.length} txs, ${chain.length} epochs)`);
